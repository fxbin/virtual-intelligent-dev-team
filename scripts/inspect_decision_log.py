def _detect_system_language() -> str:
    """Best-effort system locale detection. Falls back to English."""
    import os
    for attr in ("LC_ALL", "LANG", "LANGUAGE"):
        value = (os.environ.get(attr) or "").strip()
        if value:
            lang = value.split("_")[0].split(".")[0].lower()
            if lang in SUPPORTED_LANGUAGES:
                return lang
    try:
        loc = locale.getlocale()[0] or ""
        lang = loc.split("_")[0].lower()
        if lang in SUPPORTED_LANGUAGES:
            return lang
    except Exception:
        pass
    return DEFAULT_LANGUAGE


def resolve_language(requested: str) -> str:
    if requested == "auto":
        return _detect_system_language()
    if requested in SUPPORTED_LANGUAGES:
        return requested
    return DEFAULT_LANGUAGE


def tr(lang: str, key: str, **kwargs: Any) -> str:
    """Look up a translated string, falling back to English if a key is missing."""
    table = STRINGS.get(lang) or STRINGS[DEFAULT_LANGUAGE]
    raw = table.get(key)
    if raw is None:
        raw = STRINGS[DEFAULT_LANGUAGE].get(key, key)
    if kwargs:
        try:
            return raw.format(**kwargs)
        except (KeyError, IndexError):
            return raw
    return raw


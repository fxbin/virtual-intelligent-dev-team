def filter_entries_by_window(
    entries: list[dict[str, Any]],
    window_seconds: int | None,
    reference_dt: datetime | None = None,
) -> list[dict[str, Any]]:
    """Filter entries to those within the last `window_seconds` seconds.

    `reference_dt` defaults to the most recent timestamp found in the entries
    (or `now()` when no entries are timestamped). When `window_seconds` is
    `None` the input list is returned unchanged.
    """
    if window_seconds is None:
        return list(entries)
    if reference_dt is None:
        timestamps = [
            parse_iso(e["timestamp"]) for e in entries
            if isinstance(e.get("timestamp"), str)
        ]
        timestamps = [t for t in timestamps if t is not None]
        reference_dt = max(timestamps) if timestamps else datetime.now()
    cutoff = reference_dt - timedelta(seconds=window_seconds)
    kept: list[dict[str, Any]] = []
    for e in entries:
        ts = e.get("timestamp")
        if not isinstance(ts, str):
            continue
        dt = parse_iso(ts)
        if dt is None or dt < cutoff:
            continue
        kept.append(e)
    return kept


def parse_iso(value: str) -> datetime | None:
    if not isinstance(value, str) or "T" not in value:
        return None
    try:
        return datetime.fromisoformat(value)
    except Exception:
        return None


def load_entries(log_path: Path) -> tuple[list[dict[str, Any]], list[str]]:
    """Parse the log file. Returns (entries, warnings)."""
    entries: list[dict[str, Any]] = []
    warnings: list[str] = []
    if not log_path.exists():
        return entries, [f"log file not found: {log_path}"]
    try:
        with log_path.open("r", encoding="utf-8") as fh:
            for line_no, raw in enumerate(fh, start=1):
                stripped = raw.strip()
                if stripped == "":
                    continue
                try:
                    item = json.loads(stripped)
                except json.JSONDecodeError as exc:
                    warnings.append(f"line {line_no}: JSON decode error: {exc.msg}")
                    continue
                if not isinstance(item, dict):
                    warnings.append(f"line {line_no}: top-level value is not an object")
                    continue
                entries.append(item)
    except Exception as exc:
        warnings.append(f"failed to read log: {exc!r}")
        return entries, warnings
    return entries, warnings


def summarize(entries: list[dict[str, Any]]) -> dict[str, Any]:
    decisions = Counter()
    verifiers = Counter()
    leads = Counter()
    tracks = Counter()
    risks = Counter()
    hourly: dict[str, int] = {}
    first_dt: datetime | None = None
    last_dt: datetime | None = None
    skipped_dt = 0

    for entry in entries:
        decisions[entry.get("decision", "n_a")] += 1
        verifiers[entry.get("verifier", "n_a")] += 1
        leads[entry.get("lead_agent", "n_a")] += 1
        tracks[entry.get("selected_track", "n_a")] += 1
        risks[entry.get("risk_level", "n_a")] += 1

        ts = entry.get("timestamp")
        dt = parse_iso(ts) if isinstance(ts, str) else None
        if dt is None:
            skipped_dt += 1
            continue
        if first_dt is None or dt < first_dt:
            first_dt = dt
        if last_dt is None or dt > last_dt:
            last_dt = dt
        hour_key = dt.strftime("%Y-%m-%d %H:00")
        hourly[hour_key] = hourly.get(hour_key, 0) + 1

    # Keep the 24 most recent hours only.
    sorted_hours = sorted(hourly.items())[-24:]
    last_24h_throughput = sum(count for _, count in sorted_hours)

    return {
        "total_events": len(entries),
        "events_with_valid_timestamp": len(entries) - skipped_dt,
        "first_event": first_dt.isoformat(timespec="seconds") if first_dt else None,
        "last_event": last_dt.isoformat(timespec="seconds") if last_dt else None,
        "decision_distribution": dict(decisions),
        "verifier_distribution": dict(verifiers),
        "lead_distribution": dict(leads),
        "track_distribution": dict(tracks),
        "risk_distribution": dict(risks),
        "last_24h_throughput": last_24h_throughput,
        "hourly_throughput": dict(sorted_hours),
    }



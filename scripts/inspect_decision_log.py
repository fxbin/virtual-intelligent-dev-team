def _render_sparkline(hourly: dict[str, int], lang: str = DEFAULT_LANGUAGE) -> str:
    """Render an inline SVG sparkline for the hourly throughput series.

    The SVG uses a fixed viewBox of 800x120 with linear interpolation between
    points and a gradient fill. The peak point is highlighted in red.
    """
    if not hourly:
        return f"<div class='empty'>{tr(lang, 'no_hourly')}</div>"

    items = list(hourly.items())
    width, height = 800, 120
    pad_x, pad_y = 16, 18
    inner_w = width - pad_x * 2
    inner_h = height - pad_y * 2

    max_value = max(v for _, v in items) or 1
    n = len(items)
    step_x = inner_w / max(n - 1, 1)

    points: list[tuple[float, float]] = []
    for idx, (_, value) in enumerate(items):
        x = pad_x + idx * step_x
        y = pad_y + inner_h - (value / max_value) * inner_h
        points.append((x, y))

    line_path = " ".join(
        ("M" if idx == 0 else "L") + f"{x:.1f},{y:.1f}"
        for idx, (x, y) in enumerate(points)
    )
    area_path = (
        f"M{points[0][0]:.1f},{pad_y + inner_h:.1f} "
        + " ".join(f"L{x:.1f},{y:.1f}" for x, y in points)
        + f" L{points[-1][0]:.1f},{pad_y + inner_h:.1f} Z"
    )

    peak_idx = max(range(n), key=lambda i: items[i][1])
    peak_x, peak_y = points[peak_idx]
    peak_count = items[peak_idx][1]

    # Axis baseline
    axis = (
        f'<line class="axis" x1="{pad_x}" y1="{pad_y + inner_h:.1f}" '
        f'x2="{width - pad_x}" y2="{pad_y + inner_h:.1f}"></line>'
    )

    # Min / max y-axis labels
    y_max_label = f'<text class="label" x="{pad_x}" y="{pad_y - 4}">{max_value}</text>'
    y_zero_label = f'<text class="label" x="{pad_x}" y="{pad_y + inner_h + 14}">0</text>'

    # X-axis: first, middle, last bucket label
    def x_label(idx: int) -> str:
        x, _ = points[idx]
        return f'<text class="label" x="{x:.1f}" y="{height - 2}" text-anchor="middle">{items[idx][0][-5:]}</text>'

    x_labels = ""
    if n >= 1:
        x_labels = x_label(0)
    if n >= 3:
        x_labels += x_label(n // 2)
    if n >= 2:
        x_labels += x_label(n - 1)

    dots = "".join(
        f'<circle class="point" cx="{x:.1f}" cy="{y:.1f}" r="2.5"></circle>'
        for x, y in points
    )

    aria_label = tr(lang, "spark_aria", value=peak_count)
    return (
        f'<svg class="spark" viewBox="0 0 {width} {height}" '
        f'preserveAspectRatio="none" role="img" '
        f'aria-label="{aria_label}">'
        f'<defs><linearGradient id="sparkGradient" x1="0" x2="0" y1="0" y2="1">'
        f'<stop offset="0%" stop-color="#8b5cf6" stop-opacity="0.45"/>'
        f'<stop offset="100%" stop-color="#8b5cf6" stop-opacity="0"/>'
        f'</linearGradient></defs>'
        f'<title>{aria_label}</title>'
        f'{axis}'
        f'<path class="area" d="{area_path}"></path>'
        f'<path class="line" d="{line_path}"></path>'
        f'{dots}'
        f'<circle class="point peak" cx="{peak_x:.1f}" cy="{peak_y:.1f}" r="4.5"></circle>'
        f'{y_max_label}{y_zero_label}{x_labels}'
        f'</svg>'
    )


def build_report(
    repo_path: Path,
    log_path: Path,
    markdown_output: Path | None,
    html_output: Path | None,
    lang: str = DEFAULT_LANGUAGE,
) -> dict[str, Any]:
    entries, warnings = load_entries(log_path)
    summary = summarize(entries)
    ok = True

    if markdown_output is not None:
        try:
            markdown_output.parent.mkdir(parents=True, exist_ok=True)
            markdown_output.write_text(render_markdown(summary, log_path, lang=lang), encoding="utf-8")
        except Exception as exc:
            ok = False
            warnings.append(f"failed to write markdown output: {exc!r}")

    if html_output is not None:
        try:
            html_output.parent.mkdir(parents=True, exist_ok=True)
            # Build multi-window summaries for the dashboard.
            windows: list[tuple[str, str, dict[str, Any]]] = []
            for window_id, label_key, seconds in WINDOW_SPECS:
                filtered = filter_entries_by_window(entries, seconds)
                windows.append((window_id, label_key, summarize(filtered)))
            html_output.write_text(render_html(log_path, windows, lang=lang), encoding="utf-8")
        except Exception as exc:
            ok = False
            warnings.append(f"failed to write html output: {exc!r}")

    return {
        "ok": ok,
        "schema_version": REPORT_SCHEMA_VERSION,
        "log_file": str(log_path),
        "language": lang,
        "summary": summary,
        "markdown_output": str(markdown_output) if markdown_output is not None else None,
        "html_output": str(html_output) if html_output is not None else None,
        "warnings": warnings,
    }


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--repo",
        default=str(SKILL_DIR),
        help="Repository root used to resolve the relative log path.",
    )
    parser.add_argument(
        "--log-file",
        default=DEFAULT_LOG_PATH,
        help="Path to the decision log (relative to --repo). Default: .skill-metrics/decision-log.jsonl",
    )
    parser.add_argument(
        "--markdown-output",
        default=None,
        help="Write a Markdown report to this path.",
    )
    parser.add_argument(
        "--html-output",
        default=None,
        help="Write a self-contained HTML dashboard to this path.",
    )
    parser.add_argument(
        "--language",
        default="auto",
        choices=("auto", "en", "zh"),
        help="Report language. 'auto' picks from system locale. Default: auto.",
    )
    parser.add_argument(
        "--pretty",
        action="store_true",
        help="Pretty-print the JSON result on stdout.",
    )
    args = parser.parse_args(argv)

    repo_path = Path(args.repo).resolve()
    log_path = repo_path / args.log_file
    markdown_path = Path(args.markdown_output).resolve() if args.markdown_output else None
    html_path = Path(args.html_output).resolve() if args.html_output else None
    lang = resolve_language(args.language)

    try:
        report = build_report(repo_path, log_path, markdown_path, html_path, lang=lang)
    except Exception as exc:
        report = {"ok": False, "error": f"unexpected inspect error: {exc!r}"}

    indent = 2 if args.pretty else None
    print(json.dumps(report, ensure_ascii=False, indent=indent))
    return 0 if report.get("ok") else 2


